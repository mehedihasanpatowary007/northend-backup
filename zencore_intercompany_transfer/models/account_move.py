from odoo import api, fields, models, _
from odoo.exceptions import AccessError, UserError


class AccountMove(models.Model):
    _inherit = 'account.move'

    ict_picking_id = fields.Many2one('stock.picking', copy=False, readonly=True, index=True, ondelete='restrict')

    @api.model_create_multi
    def create(self, vals_list):
        if not self.env.su and any(vals.get('ict_picking_id') for vals in vals_list):
            raise AccessError(_('Inter-company journal entries are generated by stock validation.'))
        return super().create(vals_list)

    def write(self, vals):
        if 'ict_picking_id' in vals and any(move.ict_picking_id.id != vals['ict_picking_id'] for move in self):
            raise UserError(_('The stock link of an inter-company entry cannot be changed.'))
        if {'line_ids', 'journal_id', 'company_id', 'date'} & vals.keys() and any(move.ict_picking_id and move.state == 'posted' for move in self):
            raise UserError(_('Posted inter-company entries are locked to the stock movement.'))
        if vals.get('state') in ('draft', 'cancel') and any(move.ict_picking_id and move.state == 'posted' for move in self):
            raise UserError(_('Use the stock Return operation to reverse a posted inter-company entry.'))
        return super().write(vals)

    def _reverse_moves(self, default_values_list=None, cancel=False):
        if self.filtered('ict_picking_id'):
            raise UserError(_('Use the transfer Return operation to reverse both stock and accounting.'))
        return super()._reverse_moves(default_values_list=default_values_list, cancel=cancel)

    def button_draft(self):
        if self.filtered('ict_picking_id'):
            raise UserError(_('Inter-company entries follow physical stock. Use the transfer Return operation.'))
        return super().button_draft()

    def button_cancel(self):
        if self.filtered('ict_picking_id'):
            raise UserError(_('Inter-company entries cannot be cancelled independently of the stock transfer.'))
        return super().button_cancel()


class AccountMoveLine(models.Model):
    _inherit = 'account.move.line'

    @api.model_create_multi
    def create(self, vals_list):
        for vals in vals_list:
            move = self.env['account.move'].browse(vals.get('move_id'))
            if move.ict_picking_id and move.state == 'posted':
                raise UserError(_('Lines cannot be added to posted inter-company entries.'))
        return super().create(vals_list)

    def write(self, vals):
        if {'account_id', 'balance', 'debit', 'credit', 'amount_currency', 'currency_id', 'move_id', 'product_id'} & vals.keys():
            if any(line.move_id.ict_picking_id and line.move_id.state == 'posted' for line in self):
                raise UserError(_('Posted inter-company accounting lines are locked to the stock movement.'))
        return super().write(vals)

    @api.ondelete(at_uninstall=False)
    def _ict_protect_posted_lines(self):
        if any(line.move_id.ict_picking_id and line.move_id.state == 'posted' for line in self):
            raise UserError(_('Posted inter-company accounting lines cannot be deleted.'))
